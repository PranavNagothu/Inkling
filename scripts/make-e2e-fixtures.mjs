// Generates the tiny Phase 4 e2e fixtures (committed under e2e/fixtures/):
//   lecture-40s.wav  40 s, 8 kHz mono 8-bit PCM (a quiet hum, ~320 KB)
//   lecture-40s.vtt  matching WebVTT captions with the usual real-world noise (tags, speaker
//                    markers, a [Music] cue, a multi-line cue, hour-less timestamps)
// Usage: node scripts/make-e2e-fixtures.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "e2e", "fixtures");
mkdirSync(outDir, { recursive: true });

const DURATION_S = 40;
const SAMPLE_RATE = 8000;
const n = SAMPLE_RATE * DURATION_S;
const buf = Buffer.alloc(44 + n);
buf.write("RIFF", 0);
buf.writeUInt32LE(36 + n, 4);
buf.write("WAVE", 8);
buf.write("fmt ", 12);
buf.writeUInt32LE(16, 16);
buf.writeUInt16LE(1, 20); // PCM
buf.writeUInt16LE(1, 22); // mono
buf.writeUInt32LE(SAMPLE_RATE, 24);
buf.writeUInt32LE(SAMPLE_RATE, 28);
buf.writeUInt16LE(1, 32);
buf.writeUInt16LE(8, 34);
buf.write("data", 36);
buf.writeUInt32LE(n, 40);
for (let i = 0; i < n; i++) {
  const t = i / SAMPLE_RATE;
  const fade = Math.min(1, t / 0.5, (DURATION_S - t) / 0.5);
  const v = 0.03 * 127 * fade * Math.sin(2 * Math.PI * 147 * t);
  buf.writeUInt8(128 + Math.round(v), 44 + i);
}
writeFileSync(join(outDir, "lecture-40s.wav"), buf);

const vtt = `WEBVTT
Kind: captions
Language: en

NOTE generated by scripts/make-e2e-fixtures.mjs

00:00.000 --> 00:01.500
[Music]

1
00:01.500 --> 00:05.000
<v Professor>Welcome back. Today we look at related rates.</v>

00:05.000 --> 00:09.500
&gt;&gt; PROFESSOR: A ladder slides down a wall,
and we want how fast the top falls.

00:09.500 --> 00:14.000
Call the height <c.yellow>y</c> and the base x.

00:14.000 --> 00:18.500
The ladder length stays fixed, so x squared plus y squared is constant.

00:18.500 --> 00:23.000
Differentiate both sides with respect to time.

00:23.000 --> 00:27.500
That gives two x dx dt plus two y dy dt equals zero.

00:27.500 --> 00:32.000
<i>Now</i> solve for dy dt and plug in the numbers.

00:32.000 --> 00:36.500
The minus sign means the top is moving down.

00:36.500 --> 00:40.000
Next time: optimization problems.
`;
writeFileSync(join(outDir, "lecture-40s.vtt"), vtt);
console.log(`wrote e2e/fixtures/lecture-40s.wav (${(buf.length / 1024).toFixed(0)} KB) and lecture-40s.vtt`);
